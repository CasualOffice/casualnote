#!/usr/bin/env python3
"""Rebuild docs/20-ERROR-CODE-REGISTRY.md from the tables in the owning documents."""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
OWNER = {"PKG": ("36-EXPORT-FORMAT.md", "Export package"), "MOD": ("22-DATA-MODEL.md", "Data model"), "OPS": ("24-OPERATIONS-AND-MERGE.md", "Operations"), "MRG": ("24-OPERATIONS-AND-MERGE.md", "Merge"), "STO": ("23-STORAGE-FORMAT.md", "Storage"), "SYN": ("56-SYNC-DESIGN.md", "Sync"), "CRY": ("56-SYNC-DESIGN.md", "Cryptography"), "SRV": ("57-SERVER-DESIGN.md", "Server"), "DSK": ("44-DESKTOP-SHELL.md", "Desktop shell"), "EDT": ("42-EDITOR-AND-RENDERING.md", "Editor"), "INK": ("43-CANVAS-AND-INK.md", "Canvas and ink"), "SCH": ("60-SEARCH-AND-EMBEDDINGS.md", "Search"), "EMB": ("60-SEARCH-AND-EMBEDDINGS.md", "Embeddings"), "GRF": ("61-KNOWLEDGE-GRAPH.md", "Knowledge graph"), "AI": ("62-AI-ASSISTANT-AND-PROVIDERS.md", "Assistant"), "MDL": ("62-AI-ASSISTANT-AND-PROVIDERS.md", "Local models"), "TOL": ("63-AGENT-TOOLS-AND-MCP.md", "Agent tools"), "MCP": ("63-AGENT-TOOLS-AND-MCP.md", "MCP server"), "IMP": ("37-IMPORT-FORMATS.md", "Import")}
CODE = re.compile(r"CN-[A-Z]{2,4}-\d{4}")


def main():
    codes = {}
    for prefix, (name, _) in OWNER.items():
        for line in (DOCS / name).read_text("utf8").splitlines():
            if not line.startswith("|"):
                continue
            cells = [c.strip() for c in re.split(r"(?<!\\)\|", line.strip().strip("|"))]
            for i, cell in enumerate(cells):
                for code in CODE.findall(cell):
                    if not code.startswith(f"CN-{prefix}-"):
                        continue
                    if i == 0 and cell.strip("`") == code and len(cells) > 1:
                        meaning = cells[1]
                    else:
                        others = [x for j, x in enumerate(cells) if j != i and x and not CODE.fullmatch(x.strip("`"))]
                        if not others:
                            continue
                        meaning = others[0]
                    if code not in codes or (i == 0 and not codes[code][1]):
                        codes[code] = (meaning, i == 0)
    used = set()
    for path in [*DOCS.glob("*.md"), ROOT / "tools/cnotepack.py"]:
        if path.name != "20-ERROR-CODE-REGISTRY.md":
            used |= set(CODE.findall(path.read_text("utf8")))
    out = ["# 20 — Error code registry", "", "Stable, and never reused. **The contract:** messages carry ids and counts, never note text. Each area's document is the authority for when a code fires, and this page is the index, generated by `tools/gen-error-registry.py`. No engine exists, so only `CN-PKG-*` is implemented, in `tools/cnotepack.py`. The AI model catalogue uses `CN-MDL` because `CN-MOD` is the data model. `CN-SDK` is reserved (`FND-75`).", ""]
    for prefix, (name, title) in OWNER.items():
        here = sorted(c for c in codes if c.startswith(f"CN-{prefix}-"))
        out += [f"## {title} (`CN-{prefix}`), see [{name[:2]}]({name})", "", "| Code | Meaning |", "| --- | --- |"]
        out += [f"| {c} | {codes[c][0]} |" for c in here] + [""]
    missing = sorted(used - set(codes))
    if missing:
        out += ["## Mentioned without a definition", "", "| Code | Meaning |", "| --- | --- |"] + [f"| {c} | To be defined |" for c in missing] + [""]
    (DOCS / "20-ERROR-CODE-REGISTRY.md").write_text("\n".join(out), "utf8")
    print(f"{len(codes)} codes, {len(missing)} undefined: {missing}")


if __name__ == "__main__":
    main()
